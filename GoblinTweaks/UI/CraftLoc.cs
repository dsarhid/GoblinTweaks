    /// <summary>Active language code ("en"/"es"), set by the addon.</summary>
    public static string Lang = "en";

    public static string Get(string key)
    {
        if (Tables.TryGetValue(Lang, out var table) && table.TryGetValue(key, out var value))
            return value;
        return Tables["en"].TryGetValue(key, out var en) ? en : key;
    }

    public static string Fmt(string key, params object[] args) => string.Format(Get(key), args);

    /// <summary>"3 h ago" for data read at <paramref name="seenUtc"/>; empty when unknown or read in the last few minutes.</summary>
    public static string Age(DateTime seenUtc)
    {
        if (seenUtc == DateTime.MinValue) return string.Empty;

        var age = DateTime.UtcNow - seenUtc;
        if (age < TimeSpan.FromMinutes(5)) return string.Empty;
        if (age.TotalHours < 1) return Fmt("age.min", (int)age.TotalMinutes);
        return age.TotalDays < 1 ? Fmt("age.hours", (int)age.TotalHours) : Fmt("age.days", (int)age.TotalDays);
    }

